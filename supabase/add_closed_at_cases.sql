-- ============================================================================
-- 给 cases 表新增 closed_at 列：记录结案 / 解除委托日期
--
-- 背景：阶段（stage）只有「结案」「解除委托」这类状态字符串，没有对应的日期。
--   台账需要按「结案/解除委托日期」排序，故补一个可空的时间列。
--
-- 幂等：IF NOT EXISTS 保护，可重复执行。云端与 NAS 通用。
-- 类型用 date 即可（结案日期到天足够）；为与其他时间列一致也可用 timestamptz，
--   此处用 date，前端 DateInput type="date" 直接读写 yyyy-mm-dd。
-- ============================================================================

alter table public.cases add column if not exists closed_at date;
